def generate_fixture(
    text: str, tokenizer_name: str, tokenizer: Tokenizer
) -> Dict[str, Any]:
    """Generate a single fixture entry."""
    encoding = tokenizer.encode(text, add_special_tokens=False)
    return {"text": text, "token_ids": encoding.ids, "tokenizer": tokenizer_name}


