def generate_hf_fixtures():
    """Generate fixtures for HF tokenizers using the tokenizers library."""
    for hf_name, hf_filename in HF_FILES.items():
        hf_path = TOKENIZERS_DIR / hf_filename
        if not hf_path.exists():
            print(f"[SKIP] {hf_path} not found")
            continue

        print(f"Processing HF {hf_name}...")
        tokenizer = Tokenizer.from_file(str(hf_path))

        fixtures = []
        for name, text in get_test_texts():
            fixture = generate_fixture(text, hf_filename, tokenizer)
            fixtures.append({"name": name, **fixture})

        output_path = FIXTURES_DIR / f"hf_{hf_name}.json.zst"
        write_text_zst(output_path,
                       json.dumps(fixtures, ensure_ascii=False,
                                  indent=2).encode("utf-8"))
        print(f"  [OK] Generated {len(fixtures)} fixtures to {output_path}")


def main():
    """Generate all fixtures."""
    print("=" * 70)
    print("Generating tokenizer fixtures via HuggingFace tokenizers")
    print("=" * 70)

    generate_hf_fixtures()

    print("=" * 70)
    print("Fixture generation complete")
    print("=" * 70)


if __name__ == "__main__":
    main()
