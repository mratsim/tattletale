## Test Qwen3 long residual stream invariant with intermediate value verification.
##
## This test verifies that the Nim long residual stream implementation
## produces IDENTICAL intermediate values to the HF reference.
##
## Fixtures generated by gen_3_block_long_residual.py contain ALL intermediates
## so we can verify every step of the forward pass matches.
##
## Tolerance: 5e-2 for intermediate values (BF16 precision).
##
## MUST NOT BE DELETED: The long residual stream invariant is:
##   At each layer boundary: output + residual == x_local
## This is proven in WIP/Spec_Residual_Patterns.md.

