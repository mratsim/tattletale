## Phase 1 host test — partition math (thrfrg equivalent) + reference checks.
##
## Validates partition_A/B/C against:
##   1. Known CUTLASS fragment numbers:
##      single atom 4/2/4 regs per thread; 2×2 tiled → 64/64/64 for a
##      (128,32)×(128,32)→(128,64) problem.
##   2. tensor-layouts reference values: the tf32 A layout offset map
##      ((4,8),(2,2)):((16,1),(8,64)) gives thread t values at
##      (t%4)*16 + (t//4) + {0, 8, 64, 72}.
##   3. Algebraic disjointness + coverage (verifyFragments, which lives
##      in workspace/ceramic/tests/test_atoms_mma_partitioning.nim — it is
##      test-only, kept out of src).
## Run with: nim cpp -r workspace/ceramic/experiments/wip_mma_gemm/test_partition_host.nim

import std/[strformat, sequtils, algorithm]
import workspace/ceramic/src/int_tuples
import workspace/ceramic/src/layouts
import workspace/ceramic/src/layout_constructors
import workspace/ceramic/src/layout_indexing
import workspace/ceramic/src/layout_algebra
import workspace/ceramic/src/atoms
import workspace/ceramic/src/atoms_nvidia
import workspace/ceramic/src/atoms_mma_partitioning
import workspace/ceramic/tests/test_atoms_mma_partitioning

const atom = SM80_16x8x8_F32TF32TF32F32_TN

# ── Single atom: 1×1×1 thread tiling, 32 threads ──
const single = TiledMma[typeof(atom), typeof(make_layout((1, 1, 1)))](
  atom: atom, threadLayout: make_layout((1, 1, 1)))

# fragment counts per thread: A 4, B 2, C 4 (tile 16×8, 16×8, 16×8)
let pA = single.partition_A(16, 8)
let pB = single.partition_B(8, 8)
let pC = single.partition_C(16, 8)
doAssert cosize(pA).toIntVal() == 128
doAssert cosize(pB).toIntVal() == 64
doAssert cosize(pC).toIntVal() == 128

# reference: thread 0 A offsets = {0, 8, 64, 72}; thread 5 = 17 + {0,8,64,72}
# (partition layout indexed at the nested (T, V) coords — the atom mode
# coords come from the shape-based idx2crd(shape, flat))
let pA0 = single.partition_A(16, 8)
let tc0 = idx2crd(mode(single.atom.aLayout, 0).shape, 0)
let a0 = (0 ..< 4).mapIt(
  crd2idx(pA0, ((tc0, idx2crd(mode(single.atom.aLayout, 1).shape, it)), (0, 0), (0, 0))).toIntVal())
doAssert a0 == @[0, 8, 64, 72], &"A t0 offsets: {a0}"
let tc5 = idx2crd(mode(single.atom.aLayout, 0).shape, 5)
let a5 = (0 ..< 4).mapIt(
  crd2idx(pA0, ((tc5, idx2crd(mode(single.atom.aLayout, 1).shape, it)), (0, 0), (0, 0))).toIntVal())
doAssert a5 == @[17, 25, 81, 89], &"A t5 offsets: {a5}"
# reference: thread 0 C offsets = {0, 16, 8, 24} (SM80_16x8_Row)
let pC0 = single.partition_C(16, 8)
let c0 = (0 ..< 4).mapIt(
  crd2idx(pC0, ((tc0, idx2crd(mode(single.atom.cLayout, 1).shape, it)), (0, 0), (0, 0))).toIntVal())
doAssert c0 == @[0, 16, 8, 24], &"C t0 offsets: {c0}"
# reference: thread 0 B offsets = {0, 32}
let pB0 = single.partition_B(8, 8)
let b0 = (0 ..< 2).mapIt(
  crd2idx(pB0, ((tc0, idx2crd(mode(single.atom.bLayout, 1).shape, it)), (0, 0), (0, 0))).toIntVal())
doAssert b0 == @[0, 32], &"B t0 offsets: {b0}"

# disjointness + coverage for the single atom
single.verifyFragments(16, 8, opA)
single.verifyFragments(8, 8, opB)
single.verifyFragments(16, 8, opC)
echo "  OK — single atom partition + reference offsets"

# ── 2×2 tiled: (128,32)×(128,32) → (128,64), 128 threads ──
#   Tiled 2×2 over (128,32) → 64/64/64 per thread
#   C tile (128, 64) = 8192 / 128 threads = 64 per thread ✓
const tiled2 = TiledMma[typeof(atom), typeof(make_layout((2, 2, 1)))](
  atom: atom, threadLayout: make_layout((2, 2, 1)))

let tA = fragCoords(tiled2, opA, 32, 8, 0)   # A tile (2*16, 1*8) = (32, 8)
let tB = fragCoords(tiled2, opB, 16, 8, 0)   # B tile (2*8, 1*8) = (16, 8)
let tC = fragCoords(tiled2, opC, 32, 16, 0)  # C tile (2*16, 2*8) = (32, 16)
doAssert tA.len == 4, &"tiled A: {tA.len}"
doAssert tB.len == 2, &"tiled B: {tB.len}"
doAssert tC.len == 4, &"tiled C: {tC.len}"

# per-thread counts across the whole 128-thread warp-group
var totalA = 0
var totalC = 0
for t in 0 ..< 128:
  totalA += fragCoords(tiled2, opA, 32, 8, t).len
  totalC += fragCoords(tiled2, opC, 32, 16, t).len
# A is shared across ThrN=2 N-atoms: each element held by 2 threads
doAssert totalA == 2 * 32 * 8, &"A total {totalA} (2 copies of 32×8)"
doAssert totalC == 32 * 16, &"C total {totalC} (1 copy of 32×16)"

tiled2.verifyFragments(32, 8, opA)
tiled2.verifyFragments(16, 8, opB)
tiled2.verifyFragments(32, 16, opC)
echo "  OK — 2×2 tiled partition (128 threads) + coverage"

# ── Cross-check vs tensor-layouts tile_mma_grid (generated by the
#    Python oracle, 2026-08-08, 2×2 tiled tf32 atom) ──
doAssert fragCoords(tiled2, opC, 32, 16, 0).sorted == @[(0,0),(0,1),(8,0),(8,1)]
doAssert fragCoords(tiled2, opC, 32, 16, 1).sorted == @[(0,2),(0,3),(8,2),(8,3)]
doAssert fragCoords(tiled2, opC, 32, 16, 32).sorted == @[(16,0),(16,1),(24,0),(24,1)]
doAssert fragCoords(tiled2, opC, 32, 16, 64).sorted == @[(0,8),(0,9),(8,8),(8,9)]
doAssert fragCoords(tiled2, opA, 32, 8, 0).sorted == @[(0,0),(0,4),(8,0),(8,4)]
doAssert fragCoords(tiled2, opA, 32, 8, 5).sorted == @[(1,1),(1,5),(9,1),(9,5)]
doAssert fragCoords(tiled2, opB, 16, 8, 0).sorted == @[(0,0),(0,4)]
doAssert fragCoords(tiled2, opB, 16, 8, 5).sorted == @[(1,1),(1,5)]
echo "  OK — cross-check vs tensor-layouts tile_mma_grid"

# ── 4×4 tiled over a (128,32)×(128,32) → (128,64) problem ──
#   Verified numbers: 64/64/64 per thread, 2048 FMA
const tiled4 = TiledMma[typeof(atom), typeof(make_layout((4, 4, 1)))](
  atom: atom, threadLayout: make_layout((4, 4, 1)))
doAssert fragCoords(tiled4, opA, 64, 8, 3).len == 4
doAssert fragCoords(tiled4, opB, 32, 8, 3).len == 2
doAssert fragCoords(tiled4, opC, 64, 32, 3).len == 4
var perThread = 0
for t in 0 ..< 512:
  perThread += fragCoords(tiled4, opC, 64, 32, t).len
doAssert perThread == 64 * 32, "4×4 C tile covered by 512 threads"
tiled4.verifyFragments(64, 8, opA)
tiled4.verifyFragments(32, 8, opB)
tiled4.verifyFragments(64, 32, opC)
echo "  OK — 4×4 tiled partition (512 threads, 64/64/64 pattern)"
