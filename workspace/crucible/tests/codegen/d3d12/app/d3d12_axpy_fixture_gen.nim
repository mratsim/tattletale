## Regenerates d3d12_axpy_fixture.nim, the baked axpy DXBC/DXIL container.
## Run by hand on a machine with dxc on PATH:
##
##   nim c -r --hints:off --warnings:off \
##     --outdir:build/tests --nimcache:nimcache/tests \
##     workspace/crucible/tests/codegen/d3d12/app/d3d12_axpy_fixture_gen.nim
##
## Regenerate only when the kernel source or the dxc version changes.
## The generator's name stays outside the t_*/test_* patterns so no test
## task runs it.

import workspace/crucible
import workspace/crucible/src/runtime/errors
import workspace/crucible/src/runtime/backends/d3d12_compile
import std/[os, strutils]

proc fourccToString(word: uint32): string =
  ## Little-endian fourcc: the least significant byte is the first character.
  result = newString(4)
  result[0] = chr(word and 0xFF'u32)
  result[1] = chr((word shr 8) and 0xFF'u32)
  result[2] = chr((word shr 16) and 0xFF'u32)
  result[3] = chr((word shr 24) and 0xFF'u32)

proc escapeNimLine(line: string): string =
  result = newStringOfCap(line.len + 8)
  for c in line:
    if c == '\\' or c == '"':
      result.add('\\')
    result.add(c)

proc fixtureBody(hlsl: string, words: seq[uint32]): string =
  result = ""
  let lines = hlsl.split('\n')
  # A newline-terminated source splits into a trailing empty element,
  # so every element keeps its own newline except the last.
  for i in 0 ..< lines.len - 1:
    result.add("  \"" & escapeNimLine(lines[i]) & "\\n\" &\n")
  result.add("  \"\"\n")
  result.add("\n")
  result.add("const axpyDxbcWords*: array[" & $words.len & ", uint32] = [\n")
  var i = 0
  while i < words.len:
    var row = ""
    var j = i
    while j < min(i + 6, words.len):
      if j > i:
        row.add(", ")
      row.add("0x" & toHex(words[j], 8) & "'u32")
      inc j
    let comma = if i + 6 < words.len: "," else: ""
    result.add("  " & row & comma & "\n")
    i += 6
  result.add("]\n")

proc runTest() =
  let hlsl = hlsl:
      proc axpyKernel(output, x, y: ptr UncheckedArray[float32], alpha: float32) {.global.} =
        let i = thread_position_in_grid.x
        output[i] = alpha * x[i] + y[i]
  let words = compileHlslToDxilViaDxc(hlsl)

  let magic = fourccToString(words[0])
  echo "[d3d12] generator: container " & $words.len & " words (" & $(words.len * 4) &
      " bytes), magic \"" & magic & "\""
  if magic != "DXBC":
    failLoud("[d3d12] generator produced a container without the DXBC magic, got \"" &
        magic & "\"")

  let fixturePath = currentSourcePath().parentDir() / "d3d12_axpy_fixture.nim"
  var fixture = ""
  fixture.add("# Tattletale\n")
  fixture.add("# Copyright (c) 2026 Mamy André-Ratsimbazafy\n")
  fixture.add("# Licensed and distributed under either of\n")
  fixture.add("#   * MIT license (license terms in the root directory or at http://opensource.org/licenses/MIT).\n")
  fixture.add("#   * Apache v2 license (license terms in the root directory or at http://www.apache.org/licenses/LICENSE-2.0).\n")
  fixture.add("# at your option. This file may not be copied, modified, or distributed except according to those terms.\n")
  fixture.add("\n")
  fixture.add("## Generated by d3d12_axpy_fixture_gen.nim, do not edit by hand.\n")
  fixture.add("## Regenerate with dxc on PATH:\n")
  fixture.add("##\n")
  fixture.add("##   nim c -r --hints:off --warnings:off \\\n")
  fixture.add("##     --outdir:build/tests --nimcache:nimcache/tests \\\n")
  fixture.add("##     workspace/crucible/tests/codegen/d3d12/app/d3d12_axpy_fixture_gen.nim\n")
  fixture.add("\n")
  fixture.add("const axpyKernelHlsl* =\n")
  fixture.add(fixtureBody(hlsl, words))
  writeFile(fixturePath, fixture)
  echo "[d3d12] generator: wrote " & fixturePath

when isMainModule:
  runTest()
